// Regenerates packages/ui-website/src/googleFonts.ts from Google Fonts' public metadata.
// Run a few times a year:  node scripts/gen-google-fonts.mjs
import { writeFileSync } from "node:fs";

const CODE = { "Sans Serif": "s", "Serif": "f", "Display": "d", "Handwriting": "h", "Monospace": "m" };

const res = await fetch("https://fonts.google.com/metadata/fonts");
const json = await res.json();
const list = json.familyMetadataList
  .slice()
  .sort((a, b) => (a.popularity ?? 1e9) - (b.popularity ?? 1e9))
  .map((f) => [f.family, CODE[f.category] ?? "s"]);

const body = list.map(([fam, c]) => `["${fam.replace(/"/g, '\\"')}","${c}"]`).join(",");

const out = `// AUTO-GENERATED by scripts/gen-google-fonts.mjs — do not edit by hand.
// Source: https://fonts.google.com/metadata/fonts  (${list.length} families, most-popular first)
export type GoogleFontCategory = "Sans Serif" | "Serif" | "Display" | "Handwriting" | "Monospace";
export interface GoogleFont { family: string; category: GoogleFontCategory }

const CAT: Record<string, GoogleFontCategory> = {
  s: "Sans Serif", f: "Serif", d: "Display", h: "Handwriting", m: "Monospace",
};
const PACKED: [string, string][] = [${body}];

/** Every Google Fonts family, ordered most-popular first. */
export const GOOGLE_FONTS: GoogleFont[] = PACKED.map(([family, c]) => ({ family, category: CAT[c] }));
`;

writeFileSync(new URL("../packages/ui-website/src/googleFonts.ts", import.meta.url), out);
console.log("wrote", list.length, "families");
